BEGIN;

CREATE TABLE alembic_version (
    version_num VARCHAR(32) NOT NULL,
    CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);

-- Running upgrade  -> 0001_initial

CREATE TABLE auth_rate_limits (
    key VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL,
    window_start TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (key),
    CONSTRAINT ck_auth_attempts CHECK (attempts >= 0)
);

CREATE INDEX ix_auth_rate_window ON auth_rate_limits (window_start);

CREATE TABLE users (
    id UUID NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_users_email_normalised CHECK (email = lower(btrim(email))),
    UNIQUE (email)
);

CREATE TABLE account_sessions (
    token_digest VARCHAR(64) NOT NULL,
    user_id UUID NOT NULL,
    csrf_digest VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (token_digest),
    CONSTRAINT ck_sessions_expiry CHECK (expires_at > created_at),
    FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_account_sessions_expires_at ON account_sessions (expires_at);

CREATE INDEX ix_account_sessions_user_id ON account_sessions (user_id);

CREATE TABLE recording_sessions (
    id UUID NOT NULL,
    user_id UUID NOT NULL,
    label VARCHAR(100) NOT NULL,
    source_type VARCHAR(16) NOT NULL,
    device_label VARCHAR(100),
    original_filename VARCHAR(255) NOT NULL,
    file_digest VARCHAR(64) NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_recording_digest CHECK (file_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_recording_source CHECK (source_type IN ('recorded','synthetic')),
    CONSTRAINT ck_recording_label CHECK (length(btrim(label)) BETWEEN 1 AND 100),
    FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_recording_owner_digest UNIQUE (user_id, file_digest)
);

CREATE INDEX ix_recordings_owner_imported ON recording_sessions (user_id, imported_at DESC, id);

CREATE TABLE heart_rate_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recording_id UUID NOT NULL,
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    bpm SMALLINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_reading_bpm CHECK (bpm BETWEEN 1 AND 300),
    FOREIGN KEY(recording_id) REFERENCES recording_sessions (id) ON DELETE CASCADE,
    CONSTRAINT uq_reading_recording_time UNIQUE (recording_id, measured_at)
);

CREATE INDEX ix_readings_recording_time ON heart_rate_readings (recording_id, measured_at, id);

CREATE TABLE import_previews (
    id UUID NOT NULL,
    user_id UUID NOT NULL,
    recording_id UUID,
    file_digest VARCHAR(64) NOT NULL,
    label VARCHAR(100) NOT NULL,
    source_type VARCHAR(16) NOT NULL,
    device_label VARCHAR(100),
    original_filename VARCHAR(255) NOT NULL,
    validated_payload JSONB,
    status VARCHAR(16) DEFAULT 'pending' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT ck_preview_lifecycle CHECK ((status = 'pending' AND validated_payload IS NOT NULL AND recording_id IS NULL AND consumed_at IS NULL) OR (status = 'consumed' AND validated_payload IS NULL AND consumed_at IS NOT NULL)),
    CONSTRAINT ck_preview_digest CHECK (file_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_preview_source CHECK (source_type IN ('recorded','synthetic')),
    CONSTRAINT ck_preview_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_preview_label CHECK (length(btrim(label)) BETWEEN 1 AND 100),
    FOREIGN KEY(recording_id) REFERENCES recording_sessions (id) ON DELETE SET NULL,
    FOREIGN KEY(user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_import_previews_recording_id ON import_previews (recording_id);

CREATE INDEX ix_previews_owner_expiry ON import_previews (user_id, expires_at);

INSERT INTO alembic_version (version_num) VALUES ('0001_initial') RETURNING alembic_version.version_num;

COMMIT;
